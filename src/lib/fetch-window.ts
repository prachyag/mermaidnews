/** ตัวเลือกที่หน้าเว็บเสนอให้กด (เซิร์ฟเวอร์รับค่าอื่นใน 1–30 ได้ด้วย) */
export const FETCH_WINDOW_PRESETS = [
  { days: 1, label: "วันนี้", hint: "ข่าวใน 24 ชั่วโมงล่าสุด" },
  { days: 7, label: "7 วัน", hint: "ข่าวในสัปดาห์ที่ผ่านมา" },
  { days: 30, label: "30 วัน", hint: "ย้อนหลังได้มากที่สุด" },
] as const;

/**
 * เพดานย้อนหลัง — ข่าวเก่ากว่านี้ไม่คุ้มจะดึง
 *
 * ยิ่งย้อนไกล ยิ่งได้ข่าวที่ตกยุคจนโพสไปก็ไม่มีใครสนใจ แถมกินโควตา AI ไปกับการคัดกรอง
 * ของที่จะถูกทิ้งอยู่ดี และ Google เองก็คืนข่าวเก่ามาไม่ครบอยู่แล้ว
 */
export const MAX_FETCH_DAYS = 30;

/** ค่าเริ่มต้นเมื่อไม่ได้ระบุ — สัปดาห์เดียวคือช่วงที่ข่าวยังสดพอจะโพส */
export const DEFAULT_FETCH_DAYS = 7;

/**
 * ตรวจค่าจำนวนวันที่รับมาจากภายนอก — คืน null ถ้าใช้ไม่ได้
 *
 * จงใจ "ไม่" clamp ค่าที่เกินให้เป็น 30 เงียบ ๆ เพราะผู้ใช้ที่ขอ 365 วันแล้วได้ 30
 * โดยไม่มีใครบอก จะเข้าใจว่าระบบดึงข่าวไม่ครบ — บอกไปตรง ๆ ว่าค่าไม่ถูกต้องดีกว่า
 */
export function parseFetchDays(value: unknown): number | null {
  if (value === undefined || value === null) return DEFAULT_FETCH_DAYS;
  /*
   * รับเฉพาะ number หรือสตริงตัวเลขเท่านั้น — ห้ามโยนอะไรก็ได้เข้า Number()
   * เพราะ Number(true) = 1 และ Number([]) = 0 ทำให้ค่าที่ไม่ใช่จำนวนวันเลย
   * กลายเป็นจำนวนวันที่ดูสมเหตุสมผลได้เงียบ ๆ (เทสจับได้ตอนเขียนฟีเจอร์นี้พอดี)
   */
  if (typeof value !== "number" && typeof value !== "string") return null;
  if (typeof value === "string" && value.trim() === "") return null;
  const n = Number(value);
  if (!Number.isInteger(n) || n < 1 || n > MAX_FETCH_DAYS) return null;
  return n;
}

/** คำอธิบายช่วงเวลาแบบอ่านรู้เรื่อง ใช้ในข้อความแจ้งผล */
export function fetchWindowLabel(days: number): string {
  return days === 1 ? "วันนี้" : `${days} วันย้อนหลัง`;
}
